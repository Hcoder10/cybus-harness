"""The runtime kit every generated game ships with: small, tested engineering primitives (cleanup, springs,
motion from tokens, camera shake, sound groups, UI fitting, generated-art lookup, and the Studio-only debug relay
the harness drives captures and playtests through). The kit carries no look of its own: the look comes from each
game's style guide and tokens.
"""
from __future__ import annotations

from pathlib import Path

KIT_DIR = Path(__file__).parent
MODULES = ["Maid", "Spring", "Motion", "Shake", "Sound", "Debug", "Screen", "Assets", "TexCodec", "Textures",
           "AnimCore", "Anim", "FxMath", "CameraRig", "VFX"]

BOOT_SERVER = """-- Generated by cybus-harness: starts the Studio-only debug relay.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
require(ReplicatedStorage:WaitForChild("Kit"):WaitForChild("Debug")).initServer()
"""

BOOT_CLIENT = """-- Generated by cybus-harness: connects this client to the Studio-only debug relay.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
require(ReplicatedStorage:WaitForChild("Kit"):WaitForChild("Debug")).initClient()
"""

KIT_API = """ReplicatedStorage.Kit (require these; never copy or edit them):
- Maid.new() -> maid; maid:Give(connection|instance|function|thread) -> it; maid:Clean()
- Spring.new(initial: number|Vector2|Vector3, speed=12, damping=1) -> s; s.Target = x; s:Step(dt) -> position; s:Impulse(v); s:Snap(x)
- Motion.tween(obj, goal, kind="base"|"fast"|"slow"|"dramatic"|seconds, style?, direction?, delay?) -> Tween
  Motion.press(gui); Motion.hover(gui, on); Motion.punch(gui, amount=0.12); Motion.enter(frame, {stagger=0.04, offset=20});
  Motion.exit(frame); Motion.countUp(label, from, to, seconds, "%d")   (durations/easing come from Tokens.motion)
- Shake.kick(trauma 0..1) (client; shared camera shaker); Shake.reduceMotion = bool; Shake.new():Add(x)/:Step(dt) -> CFrame offset
- Sound.register(name, {ids={"rbxassetid://..."}, group="SFX"|"UI"|"Music"|"Ambience", volume, pitch=variance, looped});
  Sound.play(name, {parent=part?}) -> Sound; Sound.music(name, fade); Sound.duck(amount, seconds); Sound.manifest()
- Screen.gui(name, displayOrder) -> ScreenGui fitted to the 1920x1080 design canvas; Screen.isCompact(); Screen.canvas(); Screen.topInset()
- Assets.image(name, fallback?) -> content id of generated art; Assets.slice(name) -> Rect?; Assets.has(name)
- Textures.apply(inst, name) -> bool: a paint_texture texture on an ImageLabel/Button (SliceCenter too if ScaleType is Slice), ParticleEmitter,
  Beam, Trail, Decal or MeshPart; Textures.get(name) -> Content?; .preload({names}); .has/.info/.names(); .release(name); tint LA ones via ImageColor3/Color
- TexCodec.decode(data, w, h, fmt) -> RGBA8 buffer; TexCodec.checksum(buf) (Textures uses it; you rarely need it directly)
- Anim.load(character or any Motor6D rig) -> rig (cached); rig:play("clip", {fade=0.15, speed=1, weight=1, priority?, looped?,
  hold?, restart?}) -> track (a looped clip already playing returns its track); track:stop(fade); track:adjustSpeed(x);
  track:adjustWeight(w, fade); track.Marker("name"):Connect(fn); track.Ended:Connect(fn); rig:stopAll(fade);
  rig:takeOver(true) (pauses the default Animate tracks while clips play); rig:lean(1); rig:lookAt(pos|part|nil);
  rig:breathe(true); rig:recoil("RightShoulder", {rx, ry, rz}, 0.3); rig:squash(0.3); Anim.register(clip); Anim.clip(name).
  Author clips with author_clip. Transform does not replicate: play clips on each client (server fires a RemoteEvent).
- AnimCore: Anim's pure-Luau core (compile / sample / blend); you rarely need it directly
- CameraRig (client): CameraRig.follow({preset="shoulder"|"overTheTop"|"sideScroller"|"topDown", distance, height, offset, fov, pitch,
  orbit="free"|"drag"|"locked", lookAhead, speedFov={from,to,fov,pull}, collision, autoAlign, zoom={min,max,step}}) -> rig (rig:set(opts); rig:stop());
  CameraRig.shot({from=CFrame, to=CFrame | path={Vector3...}, lookAt | orbit={target,radius,height,from,to}, relativeTo, duration, hold,
  ease="Sine InOut", fov, roll, handheld, blendIn, blendOut, letterbox, slowmo}) / CameraRig.sequence({shot, ...}, {letterbox, skipInput,
  lockControls}) -> h (h:andThen(fn); h:skip()); CameraRig.kick(fovDegrees, seconds); CameraRig.punch(direction, studs); CameraRig.shake(trauma);
  CameraRig.slowmo(scale, seconds) (others read CameraRig.timeScale); the player attribute KitCinematic is true during shots
- VFX (client): VFX.preset(name, {layers={{kind="particles"|"beam"|"light"|"flash"|"ring"|"decal", delay, ...}}, budget}) once;
  VFX.play(name, at, {normal, direction, scale, intensity, follow}) -> h (h:stop()); VFX.effect(spec, at, opts); keypoints {{0,a},{0.2,b},{1,c}};
  colours Color3 | "#RRGGBB" | "Tokens.color.<name>"; VFX.flashLight(at, color, brightness, range, s); VFX.hitstop(s); VFX.screenFlash(color, s,
  strength); VFX.vignette(color, s) -> v (v:stop()); VFX.trail(part, {width, lifetime, color, transparency}) -> t (t:burst(s)); VFX.validate(spec)
- FxMath: CameraRig's and VFX's pure-Luau math (ease, springStep, keypoints, validateEffect); you rarely need it directly
- Debug.register(name, fn, description) (client or server): a command the test harness can run in Studio to show
  your screen / trigger your moment; Debug.event(name, data): log a gameplay event for playtests.
ReplicatedStorage.Shared.Tokens: Tokens.color.<role>, Tokens.font.<display|heading|body|numeric>, Tokens.size.<display|h1|h2|body|caption|numeric>,
  Tokens.space.s1..s8 (4..64), Tokens.radius.<small|medium|large> (UDim), Tokens.stroke, Tokens.motion.<fast|base|slow|dramatic>,
  Tokens.tween(kind) -> TweenInfo, Tokens.lighting.
"""


def kit_files() -> dict[str, str]:
    """Workspace-relative path -> source for the kit and its boot scripts."""
    files = {f"src/ReplicatedStorage/Kit/{m}.luau": (KIT_DIR / f"{m}.luau").read_text(encoding="utf-8") for m in MODULES}
    files["src/ServerScriptService/KitBoot.server.luau"] = BOOT_SERVER
    files["src/StarterPlayer/StarterPlayerScripts/KitBoot.client.luau"] = BOOT_CLIENT
    return files
